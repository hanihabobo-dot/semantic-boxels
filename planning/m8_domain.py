"""
m8_domain.py — M8's declared domain delta (PLAN_P4_POSE_GRASP_SAMPLERS.md
B and C) and the generator that applies it to pddl/domain_pddlstream.pddl.

With M8 OFF the planner reads the live domain file byte for byte.  With M8
ON it reads GENERATED_FILE, which is generate(live text): the live domain
plus exactly the edits below, each applied at an anchor that must occur
once.  tools/gen_bridge_domain.py writes the file; bridge_gates.py domain
(G10) regenerates it and compares.

The delta:
  - predicates (is_view ?b), (sense_view ?q ?region), (look_config ?q ?o);
  - sense gains ?q appended last, with (at_config ?q) (sense_view ?q
    ?region): the fixed eye senses only from a configuration that keeps
    the arm out of its view of the region (C1);
  - pick requires (obj_pose_known ?o) (B);
  - place, place_hiding and stack add (obj_pose_known ?o) (commanded pose,
    optimistic; B);
  - a new action observe(?o ?q): the wrist camera at a look configuration
    sets (obj_pose_known ?o) (C2).

The stream file has no delta: BF#52's test-sense-view stream was tried and
withdrawn the same evening (every IK branch over a blocked region cost a
search round); the fold it was for is static init facts
(pddlstream_planner.over_region_facts, --sense-over-region), and every run
reads STREAM_LIVE_FILE.
"""

import hashlib
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIVE_FILE = os.path.join(REPO, 'pddl', 'domain_pddlstream.pddl')
GENERATED_FILE = os.path.join(REPO, 'pddl', 'domain_pddlstream_m8.pddl')

HEADER = (";; GENERATED by tools/gen_bridge_domain.py from domain_pddlstream.pddl\n"
          ";; plus M8's declared delta (m8_domain.py).  Do not edit.\n")

# (anchor, replacement): each anchor must occur exactly once in the live file.
EDITS = (
    ("    (holding ?o)\n    (obj_pose_known ?o)\n",
     "    (holding ?o)\n    (obj_pose_known ?o)\n"
     "    ;; --- M8: observation configurations (static init facts) ---\n"
     "    (is_view ?b)                  ; pseudo-boxel of an observation configuration\n"
     "    (sense_view ?q ?region)       ; at ?q the arm keeps out of the eye's view of ?region\n"
     "    (look_config ?q ?o)           ; at ?q the wrist camera sees all of ?o\n"),
    ("    :parameters (?o ?region)\n"
     "    :precondition (and\n"
     "      (Obj ?o)\n"
     "      (Boxel ?region)\n"
     "      (handempty)\n",
     "    :parameters (?o ?region ?q)\n"
     "    :precondition (and\n"
     "      (Obj ?o)\n"
     "      (Boxel ?region)\n"
     "      (handempty)\n"
     "      (at_config ?q)                       ; M8 C1\n"
     "      (sense_view ?q ?region)\n"),
    ("      (obj_at_boxel ?o ?b)            ; Must be there\n",
     "      (obj_at_boxel ?o ?b)            ; Must be there\n"
     "      (obj_pose_known ?o)             ; M8 B: pose within the commit margin\n"),
    ("      (on_table ?o)               ; audit #41 — place lands ?o on the table\n",
     "      (on_table ?o)               ; audit #41 — place lands ?o on the table\n"
     "      (obj_pose_known ?o)         ; M8 B: commanded pose\n"),
    ("      (on_table ?o)\n"
     "      (not (holding ?o))\n"
     "      (not (is_free_space ?b))\n"
     "      (increase (total-cost) 2)\n",
     "      (on_table ?o)\n"
     "      (obj_pose_known ?o)         ; M8 B: commanded pose\n"
     "      (not (holding ?o))\n"
     "      (not (is_free_space ?b))\n"
     "      (increase (total-cost) 2)\n"),
    ("      (obj_at_boxel_KIF ?o ?o)\n",
     "      (obj_at_boxel_KIF ?o ?o)\n"
     "      (obj_pose_known ?o)         ; M8 B: commanded pose\n"),
)

OBSERVE_ACTION = """
  ;; =========================================================================
  ;; OBSERVE (M8 C2): the wrist camera re-poses ?o from a look configuration
  ;; =========================================================================
  (:action observe
    :parameters (?o ?q)
    :precondition (and
      (Obj ?o)
      (Config ?q)
      (handempty)
      (at_config ?q)
      (look_config ?q ?o)
      (obj_at_boxel ?o ?o)
    )
    :effect (and
      (obj_pose_known ?o)
      (increase (total-cost) 1)
    )
  )
"""


def generate(live_text: str) -> str:
    """The M8 domain: the live text plus the declared delta."""
    text = live_text
    for anchor, repl in EDITS:
        n = text.count(anchor)
        if n != 1:
            raise ValueError(f"M8 anchor occurs {n} times, expected once: "
                             f"{anchor.strip().splitlines()[0]!r}")
        text = text.replace(anchor, repl)
    body = text.rstrip()
    if not body.endswith(')'):
        raise ValueError("the live domain does not end with ')'")
    return HEADER + body[:-1] + OBSERVE_ACTION + ")\n"


def read(path: str) -> str:
    """The file's text as the planner reads it (universal newlines, so a
    CRLF checkout and an LF one give the same text and sha)."""
    with open(path, 'r', encoding='utf-8') as f:
        return f.read()


def sha(text: str) -> str:
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def domain_file(m8_on: bool) -> str:
    """The domain file a run loads: the generated one with M8, else the
    live one.  With M8 the generated file must equal generate(live)."""
    if not m8_on:
        return LIVE_FILE
    if not os.path.isfile(GENERATED_FILE) or \
            read(GENERATED_FILE) != generate(read(LIVE_FILE)):
        raise RuntimeError(f"{GENERATED_FILE} is missing or stale; run "
                           f"tools/gen_bridge_domain.py")
    return GENERATED_FILE


# The stream file every run reads (recorded with its sha in the run's
# domain row, G10r).  BF#52's generated stream file is gone: see the module
# docstring.
STREAM_LIVE_FILE = os.path.join(REPO, 'pddl', 'stream.pddl')
