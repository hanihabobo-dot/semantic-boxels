def _once(text: str, marker: str, what: str) -> int:
    n = text.count(marker)
    if n != 1:
        raise ValueError(f"look delta anchor occurs {n} times, expected once: {what}")
    return text.index(marker)


def generate(live_text: str, mode: str = 'boxel') -> str:
    """The look-mode domain: M8's domain with the look delta applied
    (``mode`` 'boxel' or 'centred')."""
    mode = mode_of(mode)
    if mode == 'off':
        raise ValueError("generate: mode must be 'boxel' or 'centred'")
    header, file_comment, predicates, section = (
        (HEADER, FILE_COMMENT, PREDICATES, LOOK_SECTION) if mode == 'boxel'
        else (HEADER_CENTRED, FILE_COMMENT_CENTRED, PREDICATES_CENTRED,
              LOOK_SECTION_CENTRED))
    text = m8_domain.generate(live_text)
    if not text.startswith(m8_domain.HEADER):
        raise ValueError("m8_domain.generate no longer starts with its header")
    body = text[len(m8_domain.HEADER):]

    h0 = _once(body, _HEAD_FROM, "file comment")
    h1 = _once(body, _HEAD_TO, "(define (domain")
    if not h0 < h1:
        raise ValueError("look delta anchors out of order (file comment)")
    body = body[:h0] + file_comment + body[h1:]
    _once(body, _F31_OLD, "F31 comment in place")
    body = body.replace(_F31_OLD, _F31_NEW)

    a = _once(body, _PRED_START, "(:predicates")
    b = body.index(_PRED_END, a) + len(_PRED_END)
    body = body[:a] + predicates + body[b:]

    c = _once(body, _CUT_FROM, "DERIVED PREDICATES header")
    d = _once(body, _CUT_TO, "MOVE header")
    if not c < d:
        raise ValueError("look delta anchors out of order")
    body = body[:c] + section + body[d:]

    e = _once(body, _OBSERVE, "OBSERVE header")
    body = body[:e].rstrip() + "\n)\n"
    return header + body


def read(path: str) -> str:
    return m8_domain.read(path)


def sha(text: str) -> str:
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def domain_file(look, m8_on: bool = True) -> str:
    """The domain file a run loads.  ``look`` is a --look value (or a bool,
    True meaning boxel).  Look mode needs M8's pose machinery (obj_pose_known
    gates the pick), so --look with --m8 off is refused; the generated file
    must equal generate(live)."""
    mode = mode_of(look)
    if mode == 'off':
        return m8_domain.domain_file(m8_on)
    if not m8_on:
        raise ValueError(f"--look {mode} needs --m8 on (the look builds on "
                         f"M8's pose-gated pick)")
    path = GENERATED_FILES[mode]
    if not os.path.isfile(path) or read(path) != generate(read(LIVE_FILE), mode):
        raise RuntimeError(f"{path} is missing or stale; run "
                           f"tools/gen_bridge_domain.py "
                           f"{'--look' if mode == 'boxel' else '--look-centred'}")
    return path


# ----- a small reader for the domain's own text (tests and gates) -----------

def _tokens(text: str) -> list:
    stripped = '\n'.join(line.split(';', 1)[0] for line in text.splitlines())
    out, tok = [], ''
    for ch in stripped:
        if ch in '()':
            if tok:
                out.append(tok)
                tok = ''
            out.append(ch)
        elif ch.isspace():
            if tok:
                out.append(tok)
                tok = ''
        else:
            tok += ch
    if tok:
        out.append(tok)
    return out


def parse_sexp(text: str) -> list:
    """The text as nested lists of tokens (comments dropped)."""
    stack = [[]]
    for t in _tokens(text):
        if t == '(':
            stack.append([])
        elif t == ')':
            done = stack.pop()
            stack[-1].append(done)
        else:
            stack[-1].append(t)
    if len(stack) != 1:
        raise ValueError("unbalanced parentheses")
    return stack[0]


def domain_forms(text: str, keyword: str) -> list:
    """The top-level forms of the domain that start with `keyword`."""
    top = parse_sexp(text)
    dom = next(f for f in top if isinstance(f, list) and f and f[0] == 'define')
    return [c for c in dom[1:] if isinstance(c, list) and c and c[0] == keyword]


def _fields(form: list) -> dict:
    return {form[i]: form[i + 1] for i in range(2, len(form) - 1, 2)}


def condition_atoms(formula, polarity=True):
    """(name, polarity) of every atom in a precondition or `when` condition."""
    if not isinstance(formula, list) or not formula:
        return
    head = formula[0]
    if head in ('and', 'or', 'imply'):
        for sub in formula[1:]:
            yield from condition_atoms(sub, polarity)
    elif head == 'not':
        yield from condition_atoms(formula[1], not polarity)
    elif head in ('exists', 'forall'):
        yield from condition_atoms(formula[2], polarity)
    elif head in ('increase', 'decrease', 'assign', '='):
        return
    else:
        yield head, polarity


def effect_atoms(formula, polarity=True, conditional=False):
    """(name, polarity, conditional, condition names) of every effect atom;
    atoms under a `when` are conditional and carry their condition's names."""
    if not isinstance(formula, list) or not formula:
        return
    head = formula[0]
    if head == 'and':
        for sub in formula[1:]:
            yield from effect_atoms(sub, polarity, conditional)
    elif head == 'not':
        yield from effect_atoms(formula[1], not polarity, conditional)
    elif head == 'forall':
        yield from effect_atoms(formula[2], polarity, conditional)
    elif head == 'when':
        conds = tuple(sorted({n for n, _ in condition_atoms(formula[1])}))
        for n, pol, _c, inner in effect_atoms(formula[2], polarity, True):
            yield n, pol, True, tuple(sorted(set(conds) | set(inner)))
    elif head in ('increase', 'decrease', 'assign'):
        return
    else:
        yield head, polarity, conditional, ()


def action_specs(text: str) -> dict:
    """{action: {'parameters': [...], 'pre': {(name, polarity)}, 'eff':
    {(name, polarity, conditional)}, 'eff_cond': {names in `when` conditions}}}
    for every :action of a domain text: what the PDDL says the action needs and
    does, in the form the correspondence test compares with the Python."""
    specs = {}
    for form in domain_forms(text, ':action'):
        f = _fields(form)
        eff = list(effect_atoms(f.get(':effect')))
        specs[form[1]] = {
            'parameters': f.get(':parameters'),
            'pre': set(condition_atoms(f.get(':precondition'))),
            'eff': {(n, pol, c) for n, pol, c, _ in eff},
            'eff_cond': {n for _, _, _, conds in eff for n in conds},
        }
    return specs


def derived_specs(text: str) -> dict:
    """{head predicate: set of predicate names its body uses}."""
    return {form[1][0]: {n for n, _ in condition_atoms(form[2])}
            for form in domain_forms(text, ':derived')}


def stream_predicates(stream_text: str) -> set:
    """Predicate names a stream file names in :domain and :certified."""
    names = set()

    def walk(tree):
        if isinstance(tree, list):
            if tree and isinstance(tree[0], str):
                h = tree[0]
                if not (h.startswith(':') or h.startswith('?')
                        or h in ('define', 'stream', 'and')):
                    names.add(h)
            for sub in tree:
                walk(sub)

    walk(parse_sexp(stream_text))
    return names


def predicate_uses(domain_text: str, stream_text: str = '') -> dict:
    """{declared predicate: how many times an action precondition, an effect, a
    `when` condition, a derived body or a stream names it}.  A derived
    predicate's own definition is not a use of it.  Declared and unused is 0."""
    counts = {n: 0 for n in declared_predicates(domain_text)}

    def bump(name):
        counts[name] = counts.get(name, 0) + 1

    for spec in action_specs(domain_text).values():
        for n, _ in spec['pre']:
            bump(n)
        for n, _, _ in spec['eff']:
            bump(n)
        for n in spec['eff_cond']:
            bump(n)
    for body in derived_specs(domain_text).values():
        for n in body:
            bump(n)
    for n in stream_predicates(stream_text) if stream_text else ():
        bump(n)
    return counts


def declared_predicates(text: str) -> list:
    """Names declared in a domain text's (:predicates ...) block."""
    a = text.index(_PRED_START)
    b = text.index(_PRED_END, a)
    block = text[a + len(_PRED_START):b]
    names = []
    for line in block.splitlines():
        s = line.split(';', 1)[0].strip()
        if s.startswith('(') and len(s) > 1:
            names.append(s[1:].split()[0].rstrip(')'))
    return names
