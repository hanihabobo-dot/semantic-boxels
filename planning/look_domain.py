def mode_of(value) -> str:
    """'off', 'boxel' or 'centred' for a --look value (``on`` is boxel)."""
    if value in (None, False, 'off'):
        return 'off'
    if value in (True, 'on', 'boxel'):
        return 'boxel'
    if value == 'centred':
        return 'centred'
    raise ValueError(f"unknown --look value {value!r} (off, boxel, centred)")


