"""
look_domain.py: the look-mode domain (path 9 of the dev tracks, BF#68).

With --look off the planner reads what it read before (the live domain, or
M8's generated one).  With --look on it reads GENERATED_FILE, which is
generate(live text): M8's generated domain (m8_domain.generate) with

  * the predicates block replaced by the tight one below (a predicate stays
    only if an action, a derived predicate or a stream uses it);
  * the visibility derivations and the `sense` action replaced by the look
    derivations and the `look` action;
  * the `observe` action removed (a look at an object's own boxel does its
    job).

Everything else (move, pick, place, place_hiding, stack, the costs) is the
live text with M8's edits, so a change to a shared action reaches the look
domain without a second edit.  tools/gen_bridge_domain.py --look writes the
file; tools/bridge_gates.py domain (G10) regenerates it and compares.

The contract between this action and its Python is LOOK_SPEC in
look_action.py; tests/test_look_correspondence.py compares the two.

Two looks (Hani, 2026-11-07, verbatim in tracks/look/PLAN.md section 11):
--look boxel is the one above (a viewpoint boxel, reveal facts from our boxel
model); --look centred is the reference arm that uses no boxel model in the
look: look(?o ?h ?q), the camera aimed at the centre of what it looks at (?h),
the whole of ?h in view and unblocked in the plan twin (the tag's observe rule,
straight over the centre, and for a region also from a horizontal offset),
effects as sense's, nothing about the rest of the view.
generate(live, 'centred') writes CENTRED_FILE.  The paper speaks of the
object-centred look and the boxel look.
"""

