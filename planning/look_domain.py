LOOK_SECTION = """  ;; =========================================================================
  ;; LOOK (path 9, --look on): one wrist-camera look from a free-space boxel
  ;; =========================================================================
  ;; Replaces sense and observe.  The arm is at ?q, whose camera lies inside
  ;; boxel ?v (static config_for_boxel); the camera renders once.  What a look
  ;; covers is the static fact (reveals ?q ?r): every sense point of region ?r,
  ;; or the whole box of object ?r, is in view and unhidden in the plan twin's
  ;; render at ?q.  (blocks_look_at ?x ?b ?q ?r) names a body that hides part of
  ;; that view while it stands at ?b, so a plan may relocate it first.
  ;;
  ;; The outcome is optimistic, as sense's was (the live domain's comment on
  ;; sense explains why): the effect assumes ?o is found at ?h, and when the
  ;; render shows otherwise the executor ends the plan and the loop replans
  ;; from the updated belief.  In the optimistic outcome the single target is
  ;; at ?h, so every other region the view covers is known not to hold it, and
  ;; every object the view shows completely has a known pose.  A look at an
  ;; object's own boxel (?h = ?o) is the pose look: only obj_pose_known is new.
  (:derived (look_blocked ?q ?r)
    (exists (?x ?b)
      (and (obj_at_boxel ?x ?b)
           (blocks_look_at ?x ?b ?q ?r))))

  (:derived (look_clear ?q ?r)
    (and (reveals ?q ?r)
         (not (look_blocked ?q ?r))))

  (:action look
    :parameters (?o ?h ?v ?q)
    :precondition (and
      (look_for ?o ?h)
      (Config ?q)
      (Boxel ?v)
      (handempty)
      (at_config ?q)
      (config_for_boxel ?q ?v)
      (look_clear ?q ?h)
    )
    :effect (and
      (obj_at_boxel ?o ?h)
      (obj_pose_known ?o)
      (forall (?r)
        (when (look_clear ?q ?r)
          (obj_at_boxel_KIF ?o ?r)))
      (forall (?p)
        (when (and (Obj ?p) (look_clear ?q ?p))
          (obj_pose_known ?p)))
      (increase (total-cost) 1)
    )
  )

"""

