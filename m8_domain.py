"""
m8_domain.py — M8's declared domain delta (PLAN_P4_POSE_GRASP_SAMPLERS.md
B and C) and the generator that applies it to pddl/domain_pddlstream.pddl.

With M8 OFF the planner reads the live domain file byte for byte.  With M8
ON it reads GENERATED_FILE, which is generate(live text): the live domain
plus exactly the edits below, each applied at an anchor that must occur
once.  tools/gen_bridge_domain.py writes the file; bridge_gates.py domain
(G10) regenerates it and compares.

The delta:
  - predicates (is_view ?b), (sense_view ?q ?region), (look_config ?q ?o);
  - sense gains ?q appended last, with (at_config ?q) (sense_view ?q
    ?region): the fixed eye senses only from a configuration that keeps
    the arm out of its view of the region (C1);
  - pick requires (obj_pose_known ?o) (B);
  - place, place_hiding and stack add (obj_pose_known ?o) (commanded pose,
    optimistic; B);
  - a new action observe(?o ?q): the wrist camera at a look configuration
    sets (obj_pose_known ?o) (C2).

BF#52 (2026-10-30): the stream file has a delta of its own.  With M8 OFF
the planner reads pddl/stream.pddl; with M8 ON it reads
STREAM_GENERATED_FILE = generate_stream(live text): the live streams plus
test-sense-view, which certifies (sense_view ?q ?region) for the target's
pick configurations over the region by the executor's own render rule, so
a plan senses on its way to the pick when the arm there is out of the
eye's view and returns to a static C1 spot only when it is not.
--sense-anywhere off reads the live stream file even with M8 on (the A/B).
"""

import hashlib
import os

REPO = os.path.dirname(os.path.abspath(__file__))
LIVE_FILE = os.path.join(REPO, 'pddl', 'domain_pddlstream.pddl')
GENERATED_FILE = os.path.join(REPO, 'pddl', 'domain_pddlstream_m8.pddl')

HEADER = (";; GENERATED by tools/gen_bridge_domain.py from domain_pddlstream.pddl\n"
          ";; plus M8's declared delta (m8_domain.py).  Do not edit.\n")

# (anchor, replacement): each anchor must occur exactly once in the live file.
EDITS = (
    ("    (holding ?o)\n    (obj_pose_known ?o)\n",
     "    (holding ?o)\n    (obj_pose_known ?o)\n"
     "    ;; --- M8: observation configurations (static init facts) ---\n"
     "    (is_view ?b)                  ; pseudo-boxel of an observation configuration\n"
     "    (sense_view ?q ?region)       ; at ?q the arm keeps out of the eye's view of ?region\n"
     "    (look_config ?q ?o)           ; at ?q the wrist camera sees all of ?o\n"),
    ("    :parameters (?o ?region)\n"
     "    :precondition (and\n"
     "      (Obj ?o)\n"
     "      (Boxel ?region)\n"
     "      (handempty)\n",
     "    :parameters (?o ?region ?q)\n"
     "    :precondition (and\n"
     "      (Obj ?o)\n"
     "      (Boxel ?region)\n"
     "      (handempty)\n"
     "      (at_config ?q)                       ; M8 C1\n"
     "      (sense_view ?q ?region)\n"),
    ("      (obj_at_boxel ?o ?b)            ; Must be there\n",
     "      (obj_at_boxel ?o ?b)            ; Must be there\n"
     "      (obj_pose_known ?o)             ; M8 B: pose within the commit margin\n"),
    ("      (on_table ?o)               ; audit #41 — place lands ?o on the table\n",
     "      (on_table ?o)               ; audit #41 — place lands ?o on the table\n"
     "      (obj_pose_known ?o)         ; M8 B: commanded pose\n"),
    ("      (on_table ?o)\n"
     "      (not (holding ?o))\n"
     "      (not (is_free_space ?b))\n"
     "      (increase (total-cost) 2)\n",
     "      (on_table ?o)\n"
     "      (obj_pose_known ?o)         ; M8 B: commanded pose\n"
     "      (not (holding ?o))\n"
     "      (not (is_free_space ?b))\n"
     "      (increase (total-cost) 2)\n"),
    ("      (obj_at_boxel_KIF ?o ?o)\n",
     "      (obj_at_boxel_KIF ?o ?o)\n"
     "      (obj_pose_known ?o)         ; M8 B: commanded pose\n"),
)

OBSERVE_ACTION = """
  ;; =========================================================================
  ;; OBSERVE (M8 C2): the wrist camera re-poses ?o from a look configuration
  ;; =========================================================================
  (:action observe
    :parameters (?o ?q)
    :precondition (and
      (Obj ?o)
      (Config ?q)
      (handempty)
      (at_config ?q)
      (look_config ?q ?o)
      (obj_at_boxel ?o ?o)
    )
    :effect (and
      (obj_pose_known ?o)
      (increase (total-cost) 1)
    )
  )
"""


def generate(live_text: str) -> str:
    """The M8 domain: the live text plus the declared delta."""
    text = live_text
    for anchor, repl in EDITS:
        n = text.count(anchor)
        if n != 1:
            raise ValueError(f"M8 anchor occurs {n} times, expected once: "
                             f"{anchor.strip().splitlines()[0]!r}")
        text = text.replace(anchor, repl)
    body = text.rstrip()
    if not body.endswith(')'):
        raise ValueError("the live domain does not end with ')'")
    return HEADER + body[:-1] + OBSERVE_ACTION + ")\n"


def read(path: str) -> str:
    """The file's text as the planner reads it (universal newlines, so a
    CRLF checkout and an LF one give the same text and sha)."""
    with open(path, 'r', encoding='utf-8') as f:
        return f.read()


def sha(text: str) -> str:
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def domain_file(m8_on: bool) -> str:
    """The domain file a run loads: the generated one with M8, else the
    live one.  With M8 the generated file must equal generate(live)."""
    if not m8_on:
        return LIVE_FILE
    if not os.path.isfile(GENERATED_FILE) or \
            read(GENERATED_FILE) != generate(read(LIVE_FILE)):
        raise RuntimeError(f"{GENERATED_FILE} is missing or stale; run "
                           f"tools/gen_bridge_domain.py")
    return GENERATED_FILE


# ----- BF#52: the stream delta ---------------------------------------------
# M8 C1 certified (sense_view ?q ?region) as static init facts for a few
# configurations only (the current one, q_home, the retract arc), so every
# plan moved the arm to one of them before a sense (four returns to q_home
# in Hani's seed-10 run of 2026-10-30 18:09, none of them needed).  With M8
# on the stream file gains one test stream: the same render rule
# (observe_views.ObserveViews.sense_view_test through
# streams.BoxelStreams.test_sense_view) on the configurations compute-kin
# certifies OVER the region, the target's pick configurations there, so a
# passing test folds the sense into the approach to the pick.  The
# configuration a place leaves the arm at is deliberately not a candidate:
# in Hani's 18:41 run every such test failed (the arm reaching a cell near
# the base stands in the eye's view of the farther region) and each failure
# cost a search iteration (planning 42.9 s to 166.9 s, the F7 class the
# stream file's own boxel_fits note describes).
STREAM_LIVE_FILE = os.path.join(REPO, 'pddl', 'stream.pddl')
STREAM_GENERATED_FILE = os.path.join(REPO, 'pddl', 'stream_m8.pddl')
STREAM_HEADER = (";; GENERATED by tools/gen_bridge_domain.py from stream.pddl\n"
                 ";; plus M8's declared delta (m8_domain.py).  Do not edit.\n")
SENSE_VIEW_STREAM = """
  ;; BF#52 (2026-10-30): the fixed eye senses a region from the target's
  ;; pick configuration over it when the arm there keeps out of the eye's
  ;; view, not only from the static C1 spots: a test of (configuration,
  ;; region) by the executor's own render rule in the plan twin
  ;; (observe_views.ObserveViews.sense_view_test through
  ;; streams.BoxelStreams.test_sense_view), over the configurations
  ;; compute-kin certifies for the region.  A plan then senses on its way
  ;; to the pick and returns to a C1 spot only when that configuration
  ;; blocks the view.
  (:stream test-sense-view
    :inputs (?q ?region)
    :domain (and (Config ?q) (Boxel ?region) (is_shadow ?region)
                 (config_for_boxel ?q ?region))
    :certified (sense_view ?q ?region)
  )
"""


def generate_stream(live_text: str) -> str:
    """The M8 stream file: the live text plus the test stream."""
    body = live_text.rstrip()
    if not body.endswith(')'):
        raise ValueError("the live stream file does not end with ')'")
    if '(:stream test-sense-view' in body:
        raise ValueError("the live stream file already holds test-sense-view")
    return STREAM_HEADER + body[:-1] + SENSE_VIEW_STREAM + ")\n"


def stream_file(m8_on: bool) -> str:
    """The stream file a run loads: the generated one with M8, else the
    live one.  With M8 the generated file must equal generate_stream(live)."""
    if not m8_on:
        return STREAM_LIVE_FILE
    if not os.path.isfile(STREAM_GENERATED_FILE) or \
            read(STREAM_GENERATED_FILE) != generate_stream(read(STREAM_LIVE_FILE)):
        raise RuntimeError(f"{STREAM_GENERATED_FILE} is missing or stale; run "
                           f"tools/gen_bridge_domain.py")
    return STREAM_GENERATED_FILE
